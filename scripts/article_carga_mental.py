def ts_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def ts_blocks(blocks, indent="      "):
    out = []
    for i, (typ, payload) in enumerate(blocks):
        sep = "," if i < len(blocks) - 1 else ""
        if typ == "paragraph":
            out.append(f'{indent}{{\n{indent}  type: "paragraph",\n{indent}  text: {ts_str(payload)},\n{indent}}}{sep}')
        elif typ == "heading":
            out.append(f'{indent}{{\n{indent}  type: "heading",\n{indent}  text: {ts_str(payload)},\n{indent}}}{sep}')
        elif typ == "faq":
            items = []
            for j, (q, a) in enumerate(payload):
                isep = "," if j < len(payload) - 1 else ""
                items.append(
                    f'{indent}  {{\n{indent}    question: {ts_str(q)},\n{indent}    answer: {ts_str(a)},\n{indent}  }}{isep}'
                )
            body = "\n".join(items)
            out.append(f'{indent}{{\n{indent}  type: "faq",\n{indent}  items: [\n{body},\n{indent}  ],\n{indent}}}{sep}')
    return "\n".join(out)


